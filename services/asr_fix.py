"""Починка расшифровки ПО ЗВУЧАНИЮ, до того как фраза уедет в мозг.

Распознаватель ошибается не случайно: он выдаёт слово, которое ЗВУЧИТ как сказанное. «отпрактик»
вместо «отправь», «менее реактор» вместо «мини реактор», «пятниса» вместо «пятница». Человек такое
читает без труда, потому что слышит; модель получает текст и спотыкается.

ПОЧЕМУ СЛОВАРЬ МАЛЕНЬКИЙ И ЗЛОЙ. Соблазн — «чинить всё подряд»; цена — испорченные нормальные
слова. «Менее» это настоящее русское слово, и заменить его на «мини» правильно ровно в том случае,
когда рядом «реактор». Поэтому здесь только то, на чём ломается ДЕЙСТВИЕ: её имя, глаголы команд,
названия приложений. Остальное — работа мозга, который видит контекст (см. указание в промпте:
восстанавливать смысл, а не переспрашивать).

Три предохранителя, и каждый нужен:
  * частотный стоп-лист — обычные слова не трогаем НИКОГДА, даже при похожем звучании;
  * порог схожести высокий (0.86) и длина от пяти букв — на коротких словах фонетика вырождается;
  * каждая замена пишется в журнал. Правка, которую нельзя увидеть, чинится вслепую.
"""

from __future__ import annotations

import os
import re
from difflib import SequenceMatcher

from loguru import logger

ENABLED = os.environ.get("EDIT_ASR_FIX", "1") == "1"
_MIN_LEN = 5
_RATIO = 0.86

# Что чиним: слова, на которых ломается ДЕЙСТВИЕ. Ключ — правильное написание.
_VOCAB = (
    # имя
    "пятница", "эдит", "джарвис",
    # действия
    "нарисуй", "отправь", "пришли", "скинь", "напомни", "поставь", "отмени",
    "включи", "выключи", "открой", "закрой", "покажи", "расскажи", "переведи",
    "построй", "поехали", "запиши", "запомни", "посчитай", "прочитай", "найди",
    # предметы команд
    "телеграм", "таймер", "будильник", "маршрут", "погода", "музыка", "ютуб",
    "заметка", "презентация", "реферат", "напоминание", "переписка", "камера",
    "реактор", "робот", "самолёт",
)

# Частотные слова, которые звучат похоже на что-нибудь из словаря и потому обязаны быть
# неприкосновенными. Без этого «менее» превращается в «мини», а «постой» в «поставь».
_KEEP = {
    "менее", "более", "может", "можешь", "просто", "почти", "после", "перед", "потом",
    "постой", "покажется", "правда", "правильно", "прямо", "пришлось", "прошло", "против",
    "открыто", "точно", "только", "очень", "около", "опять", "около", "нужно", "надо",
    "например", "наверное", "написал", "нашел", "нашёл", "который", "которые", "когда",
    "сейчас", "сколько", "столько", "значит", "знаешь", "думаешь", "хочешь", "будет",
    "было", "если", "чтобы", "потому", "поэтому", "вообще", "вроде", "вместе", "всегда",
}

# Русский на слух: безударные гласные сливаются (аканье/иканье), звонкие на конце оглушаются.
# Ключ строится так, чтобы «отправь» и «отпрафь» стали одной строкой.
_PHON = str.maketrans({
    "ё": "е", "о": "а", "я": "а", "э": "и", "е": "и", "ю": "у", "ы": "и",
    "б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с",
    # ц↔с: «пятниса» вместо «пятницы» — типичная ошибка распознавателя и один-единственный символ
    # разницы, из-за которого её имя не узнавалось (0.857 при пороге 0.86).
    "ц": "с",
    "ь": "", "ъ": "", "й": "и",
})


def _key(word: str) -> str:
    """Фонетический ключ: как слово ЗВУЧИТ, а не как пишется."""
    k = word.lower().translate(_PHON)
    return re.sub(r"(.)\1+", r"\1", k)          # двойные буквы на слух неразличимы


_VOCAB_KEYS = tuple((w, _key(w)) for w in _VOCAB)
_WORD_RE = re.compile(r"[а-яёА-ЯЁ]+")


def repair(text: str) -> str:
    """Вернуть фразу с исправленными по звучанию словами. Пустая/выключенная — как есть."""
    if not (ENABLED and text):
        return text

    def fix(m: re.Match) -> str:
        word = m.group(0)
        low = word.lower()
        if len(low) < _MIN_LEN or low in _KEEP:
            return word
        key = _key(low)
        best, best_ratio = "", 0.0
        for target, tkey in _VOCAB_KEYS:
            if low == target:
                return word                      # уже правильно — не трогаем
            if abs(len(tkey) - len(key)) > 2:
                continue                         # слишком разной длины, дальше не считаем
            r = SequenceMatcher(None, key, tkey).ratio()
            if r > best_ratio:
                best, best_ratio = target, r
        if best_ratio >= _RATIO and best:
            logger.info("asr-fix: {!r} -> {!r} ({:.2f})", word, best, best_ratio)
            return best
        return word

    return _WORD_RE.sub(fix, text)
